#!/usr/bin/env bash
# agent-loop.sh — Parallel dispatcher for ready-for-agent issues via eitri -b
#
# Usage:
#   ./scripts/agent-loop.sh /path/to/repo [-j N]
#
# Claims up to N open ready-for-agent issues (oldest first), adds an
# `in-progress` label to each, creates one detached git worktree per issue
# (`.worktrees/issue-N`), and runs one worker subprocess per worktree in
# parallel that drives the issue's whole build→test→review loop (T6, #1192):
# `code-build` implements and opens a PR, `code-test` gates it, then only a
# test-passing PR goes to `code-review`. Worker stdout goes to
# `.worktrees/issue-N/log` with per-stage batches streamed to `log.build` /
# `log.test` / `log.review` — never interleaved on the terminal. Workers never
# merge.
# Each stage batch's session ID is auto-generated by the shared run-ID helper
# (ADR-0025); the stage logs report the `session_id`s, and each session is
# persisted under `~/.eitri/sessions/<id>/` for post-run review instead of an
# opaque `batch-*` directory.
#
# After all workers finish, the dispatcher merges PRs serially
# (`gh pr merge --squash`), rebasing each PR branch onto the latest
# `origin/main` first, but ONLY merges an issue whose latest test verdict =
# PASS AND latest review verdict = APPROVED (the dual-gate precondition).
# `--delete-branch` is intentionally NOT used: gh's local
# branch cleanup cannot work when the head branch is checked out in its
# worktree, so it fails with exit 1 *after* the merge already landed, which
# would misreport every merge as a failure. Instead the merge outcome is
# confirmed via PR state and the remote branch is deleted explicitly.
# Rebase conflicts spawn a focused `eitri -b` resolution run inside that
# worktree (capped at 3 attempts per PR); past the
# cap the PR is left open with a comment and the dispatcher moves on.
#
# Exits 0 only when nothing was left unmerged or orphaned. Per-issue worker
# failures are reported and never stop the other workers. Ctrl+C (or SIGTERM)
# stops claiming after the current batch finishes; a second signal forces exit.
# See docs/agents/batch.md.

set -euo pipefail

# When this file is sourced (e.g. by tests reusing the verdict plumbing and the
# run_persona_batch helper on 1190/1191), define the helper functions but skip
# the dispatcher entry point. Direct invocation behaves exactly as before.
RUN_ENTRYPOINT=1
if [[ "${BASH_SOURCE[0]}" != "$0" ]]; then
	RUN_ENTRYPOINT=0
fi

REPO=""
JOBS=2

if [ "$RUN_ENTRYPOINT" -eq 1 ]; then
while [ $# -gt 0 ]; do
	case "$1" in
		-j)
			if [ $# -lt 2 ]; then
				echo "Usage: $0 /path/to/repo [-j N]" >&2
				exit 1
			fi
			JOBS="$2"
			shift 2
			;;
		-*)
			echo "Usage: $0 /path/to/repo [-j N]" >&2
			exit 1
			;;
		*)
			if [ -n "$REPO" ]; then
				echo "Usage: $0 /path/to/repo [-j N]" >&2
				exit 1
			fi
			REPO="$1"
			shift
			;;
	esac
done

if [ -z "$REPO" ]; then
	echo "Usage: $0 /path/to/repo [-j N]" >&2
	exit 1
fi

if ! [[ "$JOBS" =~ ^[0-9]+$ ]] || [ "$JOBS" -lt 1 ]; then
	echo "Error: -j must be a positive integer (got '$JOBS')" >&2
	exit 1
fi

if [ ! -d "$REPO" ]; then
	echo "Error: not a directory: $REPO" >&2
	exit 1
fi

for cmd in gh eitri jq git; do
	if ! command -v "$cmd" >/dev/null 2>&1; then
		echo "Error: required command not found: $cmd" >&2
		exit 1
	fi
done

cd "$REPO"
fi

WORKTREES_DIR=".worktrees"

# --- Cleanup ---------------------------------------------------------------

WORKTREES=()
declare -A WT_BRANCH=()

cleanup() {
	for wt in "${WORKTREES[@]:-}"; do
		[ -n "$wt" ] || continue
		local br="${WT_BRANCH[$wt]:-}"
		git worktree remove --force "$wt" 2>/dev/null || true
		if [ -n "$br" ]; then
			git branch -D "$br" 2>/dev/null || true
		fi
	done
	git worktree prune 2>/dev/null || true
}
trap cleanup EXIT

# --- Stop handling ---------------------------------------------------------

STOP_REQUESTED=0

request_stop() {
	if [ "$STOP_REQUESTED" -eq 1 ]; then
		echo "Second signal received — forcing exit" >&2
		exit 130
	fi
	STOP_REQUESTED=1
	echo "Stop requested — finishing current batch; no new issues will be claimed (send signal again to force exit)" >&2
}
trap request_stop INT TERM

# Run workers in their own session so a terminal Ctrl+C only reaches the
# dispatcher (it finishes the current batch instead of killing workers).
WORKER_SHIELD=""
if command -v setsid >/dev/null 2>&1 && setsid --wait true >/dev/null 2>&1; then
	WORKER_SHIELD="setsid --wait"
fi

# --- Verdict plumbing ---------------------------------------------------

# Extract the latest `VERDICT: APPROVED | CHANGES_REQUIRED | BLOCKED` line
# (the review gate) — or `VERDICT: PASS | REJECT` (the test gate) — from a batch
# log. Returns just the verdict name, or an empty string when the log has no
# verdict line (or is missing). A missing verdict is always treated by callers as
# a hard failure — genuinely no verdict (logger cut short, the persona refused to
# emit one) must never be mistaken for a result or a retry.
extract_verdict() {
	local log="$1" v=""
	v=$(grep -oE 'VERDICT:[[:space:]]*(APPROVED|CHANGES_REQUIRED|BLOCKED|PASS|REJECT)' "$log" 2>/dev/null | tail -1 || true)
	case "$v" in
		*APPROVED) printf '%s' 'APPROVED' ;;
		*CHANGES_REQUIRED) printf '%s' 'CHANGES_REQUIRED' ;;
		*BLOCKED) printf '%s' 'BLOCKED' ;;
		*PASS) printf '%s' 'PASS' ;;
		*REJECT) printf '%s' 'REJECT' ;;
	esac
}

# Extract the batch session id from a log. Batch runs emit their auto-generated
# session ID as a JSON slog attribute on stdout
# (internal/runner/batch.go: slog.Info("batch session", slog.String("session_id", id), ...)),
# e.g. `"msg":"batch session","session_id":"batch-<id>","session_dir":...`, so we
# parse the quoted JSON value (`"session_id":"<value>"`) instead of a bare
# `session_id=<value>`. A bare legacy form is still accepted for robustness.
# Returns the ID, or empty when the log has none (or is missing) — a genuinely
# session-less worker must never yield a false positive.
extract_session_id() {
	local log="$1" sid=""
	sid=$(grep -m1 -oE '"session_id":"[A-Za-z0-9._-]+"' "$log" 2>/dev/null | sed -E 's/.*"session_id":"([A-Za-z0-9._-]+)".*/\1/' || true)
	if [ -z "$sid" ]; then
		sid=$(grep -m1 -oE 'session_id=[A-Za-z0-9._-]+' "$log" 2>/dev/null | sed -E 's/^session_id=//' || true)
	fi
	printf '%s' "$sid"
}

# Run one persona batch in a worktree and surface its persona verdict (review
# verbs for the code-review gate, PASS/REJECT for the code-test gate).
#
# args: <wt> <stage> <persona> <prompt>
#
# Runs `eitri --persona <persona> -b "<prompt>"` inside the worktree, streaming
# output to "$wt/log.$stage", with the same worker shield and Ctrl+C handling
# (130/143 loop) as the per-issue worker phase — each call is a fresh batch with
# fresh context, so a gate evaluates the current tree objectively.
#
# Emits three lines to stdout (the caller captures and consumes them):
#   1. verdict: APPROVED | CHANGES_REQUIRED | BLOCKED | PASS | REJECT | hard-fail
#   2. the batch's exit status (hard-fail is only set when status != 0 or the
#      verdict is missing)
#   3. the per-stage log path
#
# A non-zero exit OR a missing verdict both surface as `hard-fail`; the helper
# never decides loop policy (cap / re-entry live in T6) and never blind-retries
# auth/config/lock errors that won't self-heal.
run_persona_batch() {
	local wt="$1" stage="$2" persona="$3" prompt="$4"
	local log="$wt/log.$stage" pid st=0 verdict
	( cd "$wt" && exec $WORKER_SHIELD eitri --persona "$persona" -b "$prompt" ) > "$log" 2>&1 &
	pid=$!
	while :; do
		if wait "$pid"; then
			st=0
			break
		else
			st=$?
		fi
		[ "$st" -eq 130 ] || [ "$st" -eq 143 ] || break
	done
	verdict=$(extract_verdict "$log")
	if [ "$st" -ne 0 ] || [ -z "$verdict" ]; then
		verdict="hard-fail"
	fi
	printf '%s\n%s\n%s\n' "$verdict" "$st" "$log"
}

# Run the test gate (T4, #1191): run the `code-test` persona as a fresh batch
# against an issue's worktree/PR and map its outcome to the test gate's verdict.
# Delegates to run_persona_batch (stage `test`, persona `code-test`); the persona
# runs the project's tests, decides PASS/REJECT (applying the no-test-suite
# downgrade when the project builds but has no suite), and writes the currently-
# open findings to `$wt/.test.md`. The gate only maps the verdict to
# PASS / REJECT / hard-fail: code-test `PASS`/`REJECT` pass through; a missing
# verdict, a non-zero exit, or a non-test verdict (e.g. a stray review verb)
# becomes `hard-fail` (never a blind retry). The gate does NOT decide loop policy
# — the shared 3-round cap / re-entry / merge precondition land in T6 (#1192).
#
# args: <wt> <prompt>
#
# Emits the same three lines as run_persona_batch:
#   1. PASS | REJECT | hard-fail
#   2. the batch's exit status
#   3. the per-stage log path
test_pr() {
	local wt="$1" prompt="$2" result verdict st log
	result=$(run_persona_batch "$wt" test code-test "$prompt")
	verdict=$(printf '%s\n' "$result" | sed -n '1p')
	st=$(printf '%s\n' "$result" | sed -n '2p')
	log=$(printf '%s\n' "$result" | sed -n '3p')
	case "$verdict" in
		PASS|REJECT) : ;; # acceptable test-gate verdicts
		*) verdict="hard-fail" ;; # missing/unknown verdict or hard-fail
	esac
	printf '%s\n%s\n%s\n' "$verdict" "$st" "$log"
}

# Run the review gate (T5, #1190): run the `code-review` persona as a fresh
# batch against an issue's worktree/PR and map its outcome to the review gate's
# verdict. The build→test→review order guarantees this gate only ever sees a
# test-passing PR. Delegates to run_persona_batch (stage `review`, persona
# `code-review`); the persona loads the `code-review` skill (Standards + Spec
# axes), decides APPROVED / CHANGES_REQUIRED / BLOCKED, and writes the currently-
# open review findings to `$wt/.review.md`. The gate only maps the review verbs
# through: APPROVED / CHANGES_REQUIRED / BLOCKED pass to the caller, and a
# missing verdict, a non-zero exit, or a non-review verdict (e.g. a stray test
# verb) becomes `hard-fail` (never a blind retry). The gate does NOT decide loop
# policy — the shared 3-round cap / re-entry / merge precondition land in T6
# (#1192).
#
# args: <wt> <prompt>
#
# Emits the same three lines as run_persona_batch:
#   1. APPROVED | CHANGES_REQUIRED | BLOCKED | hard-fail
#   2. the batch's exit status
#   3. the per-stage log path
review_pr() {
	local wt="$1" prompt="$2" result verdict st log
	result=$(run_persona_batch "$wt" review code-review "$prompt")
	verdict=$(printf '%s\n' "$result" | sed -n '1p')
	st=$(printf '%s\n' "$result" | sed -n '2p')
	log=$(printf '%s\n' "$result" | sed -n '3p')
	case "$verdict" in
		APPROVED|CHANGES_REQUIRED|BLOCKED) : ;; # acceptable review-gate verdicts
		*) verdict="hard-fail" ;; # missing/unknown verdict or hard-fail
	esac
	printf '%s\n%s\n%s\n' "$verdict" "$st" "$log"
}


# --- Loop orchestration (T6, #1192) ------------------------------------------

# Run the build gate: run the code-build persona as a fresh batch and map its
# outcome to OK / hard-fail. Unlike the test/review gates, the implementer
# persona does NOT emit a VERDICT line — build success is simply a clean exit
# (it implements the issue and opens/pushes a PR). A non-zero exit maps to
# hard-fail (never a blind retry).
build_pr() {
	local wt="$1" prompt="$2" result verdict st log
	result=$(run_persona_batch "$wt" build code-build "$prompt")
	verdict=$(printf '%s\n' "$result" | sed -n '1p')
	st=$(printf '%s\n' "$result" | sed -n '2p')
	log=$(printf '%s\n' "$result" | sed -n '3p')
	# verdict may be empty (no VERDICT line) on a clean build — treat st 0 as OK.
	if [ "$st" -ne 0 ]; then
		verdict="hard-fail"
	else
		verdict="OK"
	fi
	printf '%s\n%s\n%s\n' "$verdict" "$st" "$log"
}

# Persist the latest gate verdict for an issue so the dispatcher's merge gate can
# decide mergeability after the worker subshell exits. Verdicts are stored as
# plain files in the worktree (<kind>=test|review) and overwritten each gate pass so
# only the LATEST verdict survives.
store_verdict() {
	local wt="$1" kind="$2" verdict="$3"
	printf '%s\n' "$verdict" > "$wt/.$kind-verdict"
}

latest_verdict() {
	local wt="$1" kind="$2"
	local v=""
	v=$(cat "$wt/.$kind-verdict" 2>/dev/null || true)
	if [ -z "$v" ]; then
		v="NONE"
	fi
	printf '%s' "$v"
}

# True only when bash tracks the LATEST test verdict = PASS AND the LATEST review
# verdict = APPROVED — the dual-gate merge precondition.
can_merge_issue() {
	local wt="$1"
	[ "$(latest_verdict "$wt" test)" = "PASS" ] && [ "$(latest_verdict "$wt" review)" = "APPROVED" ]
}

# Run one issue's full build→test→review pipeline as the worker phase (T6, #1192).
# Orchestration is pure bash; every stage is a fresh code-build / code-test /
# code-review batch. Test REJECT and review CHANGES_REQUIRED bounce back to a
# fresh build round; review BLOCKED consumes the shared cap immediately. The cap
# of 3 shared rounds is consumed by either reject path; past it (or on BLOCKED /
# any hard-fail) the PR is left open with a "needs human" comment and the issue
# moves on. The dispatcher merges later only when can_merge_issue holds.
run_issue_phase() {
	local wt="$1" num="$2" title="$3"
	local round=0 max_rounds=3
	local verdict pr needs_human=""
	local phase_prompt

	while [ "$round" -lt "$max_rounds" ]; do
		round=$((round + 1))
		echo "Issue #$num: build→test→review round $round/$max_rounds"

		pr=$(find_pr "$num" || true)
		if [ "$round" -eq 1 ]; then
			phase_prompt=$(build_prompt "$num" "$title")
		else
			phase_prompt=$(build_fix_prompt "$num" "$title" "$pr" "$wt")
		fi

		# Build: run code-build fresh to implement (round 1) or address findings.
		verdict=$(build_pr "$wt" "$phase_prompt" | sed -n '1p')
		if [ "$verdict" = "hard-fail" ]; then
			store_verdict "$wt" test hard-fail
			echo "Issue #$num: build hard-fail — leaving PR open; moving on"
			needs_human="build stage hard-failed"
			break
		fi

		# Test gate — a test-failing PR never reaches review.
		phase_prompt=$(test_prompt "$num" "$title" "$pr")
		verdict=$(test_pr "$wt" "$phase_prompt" | sed -n '1p')
		if [ "$verdict" = "REJECT" ]; then
			store_verdict "$wt" test REJECT
			echo "Issue #$num: test REJECT (round $round)"
			if [ "$round" -ge "$max_rounds" ]; then
				needs_human="test rejected after $max_rounds rounds"
			fi
			continue
		fi
		if [ "$verdict" = "hard-fail" ]; then
			store_verdict "$wt" test hard-fail
			echo "Issue #$num: test gate hard-fail — leaving PR open; moving on"
			needs_human="test gate hard-failed"
			break
		fi
		store_verdict "$wt" test PASS

		# Review gate — only a test-passing PR is reviewed.
		phase_prompt=$(review_prompt "$num" "$title" "$pr")
		verdict=$(review_pr "$wt" "$phase_prompt" | sed -n '1p')
		case "$verdict" in
			APPROVED)
				store_verdict "$wt" review APPROVED
				echo "Issue #$num: review APPROVED (round $round) — ready to merge"
				needs_human=""
				break
				;;
			CHANGES_REQUIRED)
				store_verdict "$wt" review CHANGES_REQUIRED
				echo "Issue #$num: review CHANGES_REQUIRED (round $round)"
				if [ "$round" -ge "$max_rounds" ]; then
					needs_human="review required changes after $max_rounds rounds"
					break
				fi
				;;
			BLOCKED)
				store_verdict "$wt" review BLOCKED
				echo "Issue #$num: review BLOCKED — consumes the fix cap immediately"
				needs_human="review blocked"
				break
				;;
			hard-fail)
				store_verdict "$wt" review hard-fail
				echo "Issue #$num: review gate hard-fail — leaving PR open; moving on"
				needs_human="review gate hard-failed"
				break
				;;
		esac
	done

	if [ -n "$needs_human" ]; then
		echo "Issue #$num: $needs_human — needs human"
		pr=$(find_pr "$num" || true)
		if [ -n "$pr" ]; then
			gh pr comment "$pr" --body "Dispatcher: ${needs_human}. Needs human intervention before automatic merging." >/dev/null 2>&1 || true
		fi
	fi
}

# Print a reviewable per-issue worker summary for the dispatcher (issue #1215).
# For each stage log that is present (build / test / review / resolve) this
# reports the stage's latest verdict (extract_verdict; empty when the persona
# emits no VERDICT line, e.g. a clean build or a resolve run), the batch
# session ID auto-generated for that batch (extract_session_id), and the route
# to that batch's persisted session trail under ~/.eitri/sessions/<id>/. The
# resolve stage runs inside merge_pr and streams to log.resolve, so it is
# included here only when a rebase-conflict resolution actually ran. Each batch
# streams to its own per-stage log file, so parallel workers never interleave
# on the terminal. The worker's overall exit status and wall-clock duration are
# passed in as $3/$4 (measured by the dispatcher around wait).
#
# args: <wt> <num> <status> <seconds>
print_issue_summary() {
	local wt="$1" num="$2" st="$3" dur="$4"
	local stage verdict sid
	echo "Issue #$num worker: exit=$st duration=${dur}s"
	for stage in build test review resolve; do
		[ -f "$wt/log.$stage" ] || continue
		verdict=$(extract_verdict "$wt/log.$stage")
		[ -n "$verdict" ] || verdict="(none)"
		sid=$(extract_session_id "$wt/log.$stage")
		if [ -n "$sid" ]; then
			echo "  stage $stage: verdict=$verdict session_id=$sid -> ~/.eitri/sessions/$sid/"
		else
			echo "  stage $stage: verdict=$verdict (no batch session)"
		fi
	done
}

# --- Sandbox check ---------------------------------------------------------

ensure_sandbox_git_writable() {
	# eitri's default bwrap sandbox binds the filesystem read-only and punches
	# writable holes only for the workspace and extra_writable_paths. The git
	# metadata for a worktree lives in the *main* repo's .git dir
	# (.git/worktrees/issue-N), which is read-only unless explicitly bound
	# writable. Workers then cannot commit/push inside the worktree; they fall
	# back to shadow-repo hacks that leave the worktree detached and dirty,
	# which silently breaks the rebase/merge queue below. Fail early with an
	# actionable message instead.
	local cfg="${EITRI_CONFIG:-$HOME/.eitri/config.json}"
	local profile="default"
	if [ -f "$cfg" ]; then
		profile=$(jq -r '.sandbox.profile // "default"' "$cfg")
	fi
	# Profile "none" disables the sandbox entirely — git works.
	if [ "$profile" = "none" ]; then
		return 0
	fi
	# If bwrap is missing or unusable, eitri falls back to direct execution.
	if ! command -v bwrap >/dev/null 2>&1 || ! bwrap --ro-bind / / true >/dev/null 2>&1; then
		return 0
	fi
	# Default profile: the main repo's git dir must be writable in the sandbox.
	local gitdir repo
	gitdir=$(git rev-parse --absolute-git-dir 2>/dev/null || echo "$REPO/.git")
	repo=$(cd "$REPO" && pwd -P)
	if [ -f "$cfg" ] && jq -e --arg d "$gitdir" --arg r "$repo" \
		'.sandbox.extra_writable_paths // [] | any(. == $d or . == $r or . == ($r + "/"))' "$cfg" >/dev/null 2>&1; then
		return 0
	fi
	echo "Error: eitri sandbox (profile '$profile') blocks git writes to $gitdir" >&2
	echo "       Worktree git metadata lives there; workers cannot commit/push, breaking the merge queue." >&2
	echo "       Add it to the sandbox's writable paths in $cfg:" >&2
	echo "       \"sandbox\": { \"profile\": \"default\", \"extra_writable_paths\": [\"$gitdir\"] }" >&2
	return 1
}

# --- Labels ----------------------------------------------------------------

ensure_in_progress_label() {
	# gh refuses to add a label that does not exist; create it on demand.
	if gh label list --json name --jq 'any(.name == "in-progress")' 2>/dev/null | grep -q true; then
		return 0
	fi
	echo "Creating missing in-progress label"
	if ! gh label create in-progress --color "fbca04" --description "Issue currently being worked on by an agent" >/dev/null 2>&1; then
		echo "Error: in-progress label is missing and could not be created (insufficient permissions?)" >&2
		return 1
	fi
}

# --- Crash recovery --------------------------------------------------------

cleanup_stale_claims() {
	# A previous dispatcher may have died between claiming an issue and
	# cleaning up. Drop in-progress labels whose worktree no longer exists so
	# those issues can be picked again.
	local num
	for num in $(gh issue list --label in-progress --state open --json number --jq '.[].number' 2>/dev/null || true); do
		if [ ! -d "$WORKTREES_DIR/issue-$num" ]; then
			echo "Removing stale in-progress label from issue #$num (no worktree)"
			gh issue edit "$num" --remove-label in-progress >/dev/null 2>&1 || true
		fi
	done
}

# --- Prompts ---------------------------------------------------------------

build_prompt() {
	local num="$1" title="$2"
	cat <<EOF
---
Description: Implement issue #${num} — ${title}
---

Implement the GitHub issue #${num} — ${title}. You are working in a detached git worktree.

Step 1:
- [ ] Create a branch for the implementation
- [ ] Implement the work described in the GitHub issue using the \`tdd\` skill if possible
- [ ] Update any relevant documentation
- [ ] Run \`make test\` and fix any issues found
- [ ] Commit and push changes to git
- [ ] Create a GitHub pull request whose description contains \`Closes #${num}\`

Do NOT merge the pull request — merging is handled serially by the dispatcher.
Do NOT switch to or check out \`main\` (it is checked out in the primary worktree),
and do NOT delete branches — the dispatcher owns cleanup.

No user confirmation required for \`ready-for-agent\` issues
EOF
}

build_fix_prompt() {
	local num="$1" title="$2" pr="$3" wt="$4"
	cat <<EOF
---
Description: Implement issue #${num} — ${title} (fix round)
---

Re-enter the build for issue #${num} as a fresh fix round${pr:+ on PR #${pr}}. Close out the currently-open
handoff findings below, update documentation (including CHANGELOG.md under
\x60## [Unreleased]\x60), run the tests and fix anything you introduced, then push the new
commits to the existing PR branch. Do NOT open a second PR and do NOT merge.

Read both handoff files in the worktree before touching anything:
\x60.test.md\x60 and \x60.review.md\x60 (currently-open findings only).

Test findings (.test.md):
$( [ -f "$wt/.test.md" ] && cat "$wt/.test.md" || echo "(no test findings)" )

Review findings (.review.md):
$( [ -f "$wt/.review.md" ] && cat "$wt/.review.md" || echo "(no review findings)" )

You MUST NOT merge a pull request and MUST NOT touch \x60main\x60.
No user confirmation required for \x60ready-for-agent\x60 issues
EOF
}

# Prompt handed to the code-test gate: verify the issue's current branch/PR.
test_prompt() {
	local num="$1" title="$2" pr="$3"
	cat <<EOF
Verify issue #${num} — ${title}${pr:+ (PR #${pr})}. Identify the project's build and test
commands, build the project, and run the suite in this worktree. Write the
currently-open test findings to \x60.test.md\x60, then end your log with EXACTLY one
final \x60VERDICT: PASS\x60 or \x60VERDICT: REJECT\x60 line (apply the no-test-suite
downgrade and note it when the project builds but has no suite).
EOF
}

# Prompt handed to the code-review gate: review the test-passing PR against the issue.
review_prompt() {
	local num="$1" title="$2" pr="$3"
	cat <<EOF
Review PR #${pr} (issue #${num} — ${title}) against the originating issue. Use the
\x60code-review\x60 skill (Standards + Spec axes). Verify every issue requirement is
implemented, the CHANGELOG has an entry under \x60## [Unreleased]\x60 (unless the issue
says none is needed), and there is no scope creep. Write currently-open review
findings to \x60.review.md\x60, then end your log with EXACTLY one final
\x60VERDICT: APPROVED\x60, \x60VERDICT: CHANGES_REQUIRED\x60, or \x60VERDICT: BLOCKED\x60 line.
EOF
}

build_resolve_prompt() {
	local branch="$1" pr="$2"
	cat <<EOF
Resolve the rebase conflicts on branch ${branch} (PR #${pr}).

Run \`git status\` to see the conflicted files, resolve them, then
\`git add\` the resolved files and \`git rebase --continue\`.
Finally \`git push --force origin HEAD:${branch}\` to update the PR.
Do NOT merge the PR and do NOT switch branches.
EOF
}

# --- Issue claiming --------------------------------------------------------

claim_issues() {
	# Oldest N open ready-for-agent issues without an in-progress label
	# (and without issue-type:parent, matching the previous prompt's constraint).
	gh issue list --label ready-for-agent --state open \
		--json number,title,labels \
		--jq 'sort_by(.number) | .[] |
			select(([.labels[].name] | index("in-progress")) | not) |
			select(([.labels[].name] | index("issue-type:parent")) | not) |
			.number' \
		2>/dev/null | head -n "$JOBS" || true
}

# --- PR lookup / merge -----------------------------------------------------

find_pr() {
	local num="$1"
	# The open PR whose description references "Closes #num".
	gh pr list --state open --json number,body,headRefName \
		--jq ".[] | select(.body != null) | select(.body | test(\"#${num}\\\\b\"; \"i\")) | .number" \
		2>/dev/null | head -n 1 || true
}

wait_for_rebase_finish() {
	# Wait up to GRACE seconds for an in-progress rebase (REBASE_HEAD) to
	# finish. Resolution agents routinely complete the rebase and force-push a
	# moment before their subprocess teardown lands, so REBASE_HEAD can still be
	# present right after the resolution run exits; the single immediate check
	# races that teardown and aborts an already-finished rebase. Returns 0 once
	# the rebase is gone, 1 if it is still in progress after the grace period.
	local wt="$1" grace="${2:-10}" i=0
	while [ "$i" -lt "$grace" ] && git -C "$wt" rev-parse -q --verify REBASE_HEAD >/dev/null 2>&1; do
		sleep 1
		i=$((i + 1))
	done
	! git -C "$wt" rev-parse -q --verify REBASE_HEAD >/dev/null 2>&1
}

merge_pr() {
	local num="$1" pr="$2" branch="$3"
	local wt="$WORKTREES_DIR/issue-$num"
	local attempts=0 merged=0

	while [ "$attempts" -lt 3 ]; do
		attempts=$((attempts + 1))

		git -C "$wt" fetch origin main >/dev/null 2>&1 || true
		# Abort any stale in-progress rebase (e.g. a resolution run that did
		# not finish) so the next attempt starts from a clean tree.
		if git -C "$wt" rev-parse -q --verify REBASE_HEAD >/dev/null 2>&1; then
			git -C "$wt" rebase --abort >/dev/null 2>&1 || true
		fi
		if ! git -C "$wt" rebase origin/main >/dev/null 2>&1; then
			# Rebase conflict — spawn a focused resolution run in the worktree.
			echo "Rebase conflict on PR #$pr (issue #$num) — resolution run $attempts/3"
			local resolve_prompt rpid rst=0
			resolve_prompt=$(build_resolve_prompt "$branch" "$pr")
			( cd "$wt" && exec $WORKER_SHIELD eitri --persona generic -b "$resolve_prompt" ) > "$wt/log.resolve" 2>&1 &
			rpid=$!
			while :; do
				if wait "$rpid"; then
					rst=0
					break
				else
					rst=$?
				fi
				[ "$rst" -eq 130 ] || [ "$rst" -eq 143 ] || break
			done
			if [ "$rst" -ne 0 ]; then
				echo "Warning: resolution run for PR #$pr failed (attempt $attempts/3)" >&2
				continue
			fi
			# The agent may have completed the rebase (and force-push) a moment
			# before its teardown landed — poll briefly instead of racing the
			# single immediate check and aborting an already-finished rebase.
			if ! wait_for_rebase_finish "$wt"; then
				echo "Warning: rebase still in progress after resolution run for PR #$pr — aborting rebase" >&2
				git -C "$wt" rebase --abort >/dev/null 2>&1 || true
				continue
			fi
		fi
		git -C "$wt" push --force origin "HEAD:$branch" >/dev/null 2>&1 || true

		# Merge WITHOUT --delete-branch (see header comment): gh's local branch
		# cleanup cannot delete the head branch while it is checked out in this
		# worktree, so gh exits non-zero even though the merge already landed.
		# Judge success by PR state instead of gh's exit code; gh can also fail
		# transiently while GitHub recomputes mergeability after the force-push.
		gh pr merge "$pr" --squash >/dev/null 2>&1 || true
		if [ "$(gh pr view "$pr" --json state --jq '.state' 2>/dev/null)" = "MERGED" ]; then
			echo "Merged PR #$pr (issue #$num)"
			git push origin --delete "$branch" >/dev/null 2>&1 || true
			merged=1
			break
		fi
		sleep 5
		echo "Warning: merge of PR #$pr (issue #$num) failed (attempt $attempts/3); retrying" >&2
	done

	if [ "$merged" -ne 1 ]; then
		echo "Error: could not merge PR #$pr (issue #$num) after 3 attempts — leaving open" >&2
		gh pr comment "$pr" \
			--body "Dispatcher could not merge this PR (rebase conflicts or merge failure). Needs human intervention." \
			>/dev/null 2>&1 || true
		return 1
	fi
	return 0
}

# --- Main loop -------------------------------------------------------------

main() {
	local failures=0

	git worktree prune 2>/dev/null || true
	if ! ensure_sandbox_git_writable; then
		exit 1
	fi
	if ! ensure_in_progress_label; then
		exit 1
	fi
	cleanup_stale_claims

	while true; do
		if [ "$STOP_REQUESTED" -eq 1 ]; then
			echo "Stop requested — not claiming more issues."
			break
		fi
		if ! git fetch origin main >/dev/null 2>&1; then
			echo "Error: git fetch origin main failed" >&2
			exit 1
		fi

		local issues
		issues=$(claim_issues)
		if [ -z "$issues" ]; then
			echo "No ready-for-agent issues remain. Done."
			break
		fi

		echo "Claimed $(echo "$issues" | wc -l | tr -d ' ') issue(s): $(echo "$issues" | tr '\n' ' ')"
		local pids=() num title pid wt spawned=0

		# Claim + spawn one worker per issue.
		for num in $issues; do
			if ! gh issue edit "$num" --add-label in-progress >/dev/null 2>&1; then
				echo "Warning: could not claim issue #$num (add-label failed); skipping" >&2
				continue
			fi
			if ! git worktree add "$WORKTREES_DIR/issue-$num" --detach origin/main >/dev/null 2>&1; then
				echo "Warning: could not create worktree for issue #$num; releasing claim" >&2
				gh issue edit "$num" --remove-label in-progress >/dev/null 2>&1 || true
				continue
			fi
			WORKTREES+=("$WORKTREES_DIR/issue-$num")
			title=$(gh issue view "$num" --json title --jq '.title' 2>/dev/null || echo "issue #$num")
			echo "Starting worker for issue #$num — $title"
			# The worker phase is the build→test→review pipeline (T6, #1192): a
			# bounded fix loop over the code-build / code-test / code-review
			# personas with a dual-gate merge precondition. Each stage's batch
			# session ID is auto-generated by the shared run-ID helper; the stage
			# logs carry the `session_id` and the review trail (snapshot, HTTP
			# traces, timeline) lands in `~/.eitri/sessions/<id>/`.
			# Sourcing agent-loop.sh only defines helpers (entries are guarded),
			# then run_issue_phase drives the per-issue loop from the repo root so
			# each stage batch runs in its own worktree via run_persona_batch.
			( cd "$REPO" && exec $WORKER_SHIELD bash -c 'source scripts/agent-loop.sh; run_issue_phase "$1" "$2" "$3"' _ "$WORKTREES_DIR/issue-$num" "$num" "$title" ) > "$WORKTREES_DIR/issue-$num/log" 2>&1 &
			pid=$!
			pids+=("$num:$pid")
			spawned=$((spawned + 1))
		done

		if [ "$spawned" -eq 0 ]; then
			echo "Error: could not spawn any workers (claim or worktree creation failed) — aborting" >&2
			exit 1
		fi

		# Wait for all workers; report per-issue exit status.
		# wait returns >128 when interrupted by a trapped signal — retry then
		# instead of mistaking the signal for a worker failure.
		for entry in "${pids[@]:-}"; do
			[ -n "$entry" ] || continue
			num=${entry%%:*}
			pid=${entry##*:}
			st=0
			t0=$SECONDS
			while :; do
				if wait "$pid"; then
					st=0
					break
				else
					st=$?
				fi
				[ "$st" -eq 130 ] || [ "$st" -eq 143 ] || break
			done
			if [ "$st" -eq 0 ]; then
				echo "Worker for issue #$num succeeded"
			else
				echo "Warning: worker for issue #$num failed (exit $st)" >&2
			fi
			# Rich per-issue telemetry (issue #1215): worker status + wall-clock
			# duration plus each stage that ran, its verdict, and the route to that
			# batch's persisted session trail. Bundled into ONE helper so the block
			# stays reviewable and stays out of the per-issue worker logs.
			print_issue_summary "$WORKTREES_DIR/issue-$num" "$num" "$st" "$((SECONDS - t0))"
		done

		# Serialized merge queue: every issue with an open PR goes through it,
		# even if its worker failed, but only the dual-gate precondition (latest
		# test = PASS AND latest review = APPROVED) may actually merge (T6, #1192).
		for num in $issues; do
			wt="$WORKTREES_DIR/issue-$num"
			[ -d "$wt" ] || continue
			local pr branch
			pr=$(find_pr "$num")
			if [ -z "$pr" ]; then
				echo "Error: no open PR found for issue #$num — left unmerged/orphaned" >&2
				failures=$((failures + 1))
				continue
			fi
			if ! can_merge_issue "$wt"; then
				# PR not gated for merge — leave it open for a human.
				echo "Issue #$num: not merging PR #$pr (test=$(latest_verdict "$wt" test) review=$(latest_verdict "$wt" review)) — leaving open for review" >&2
				gh pr comment "$pr" --body "Dispatcher: merge precondition not met (latest test=$(latest_verdict "$wt" test), latest review=$(latest_verdict "$wt" review)). Needs human review." >/dev/null 2>&1 || true
				failures=$((failures + 1))
				continue
			fi
			branch=$(gh pr view "$pr" --json headRefName --jq '.headRefName' 2>/dev/null || true)
			if [ -z "$branch" ]; then
				echo "Error: could not resolve branch for PR #$pr (issue #$num)" >&2
				failures=$((failures + 1))
				continue
			fi
			WT_BRANCH["$wt"]="$branch"
			if ! merge_pr "$num" "$pr" "$branch"; then
				failures=$((failures + 1))
			fi
		done
	done

	if [ "$failures" -gt 0 ]; then
		echo "Dispatcher finished with $failures leftover(s) — see log above" >&2
		exit 1
	fi
	echo "All ready-for-agent issues processed cleanly."
}

if [ "$RUN_ENTRYPOINT" -eq 1 ]; then
	main
fi
